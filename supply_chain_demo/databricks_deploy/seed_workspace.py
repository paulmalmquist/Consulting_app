def build_demand_supply_gap():
    po = spark.read.table(table_ref(SILVER, "fact_order_cycle"))
    po = po.withColumn("period_month", F.date_trunc("month", "po_date"))
    demand = po.groupBy("sku_id", "period_month").agg(F.sum("ordered_qty").alias("demand_qty"))

    ship = spark.read.table(table_ref(SILVER, "fact_shipment_event"))
    ship = ship.withColumn("period_month", F.date_trunc("month", "ship_date"))
    supply = ship.groupBy("sku_id", "period_month").agg(F.sum("shipped_qty").alias("supply_qty"))

    gap = demand.join(supply, on=["sku_id", "period_month"], how="outer")
    gap = gap.withColumn("gap_qty",
        F.coalesce(F.col("supply_qty"), F.lit(0)) - F.coalesce(F.col("demand_qty"), F.lit(0)))
    gap = gap.withColumn("gap_pct",
        F.when(F.col("demand_qty") > 0,
               F.round((F.col("gap_qty") / F.col("demand_qty")) * 100, 2)).otherwise(None))
    gap.write.format("delta").mode("overwrite").saveAsTable(table_ref(SEMANTIC, "demand_supply_gap"))
    return gap.count()


def build_logistics_cost_to_serve():
    df = spark.read.table(table_ref(SILVER, "fact_shipment_event"))
    df = df.filter(F.col("ship_date").isNotNull())
    df = df.withColumn("period_month", F.date_trunc("month", "ship_date"))
    df = df.join(spark.read.table(table_ref(SILVER, "dim_supplier"))
                     .select("supplier_id", "supplier_name", "region"),
                 on="supplier_id", how="left")
    agg = df.groupBy("supplier_id", "supplier_name", "region", "warehouse_id", "period_month").agg(
        F.count("*").alias("shipment_count"),
        F.sum("freight_cost").alias("total_freight_cost"),
        F.sum("shipped_qty").alias("total_units"),
    )
    agg = agg.withColumn("cost_per_unit",
        F.when(F.col("total_units") > 0,
               F.round(F.col("total_freight_cost") / F.col("total_units"), 4)).otherwise(None))
    agg.write.format("delta").mode("overwrite").saveAsTable(table_ref(SEMANTIC, "logistics_cost_to_serve"))
    return agg.count()


def build_production_throughput_summary():
    df = spark.read.table(table_ref(SILVER, "fact_production_output"))
    df = df.withColumn("period_month", F.date_trunc("month", "event_date"))
    df = df.join(spark.read.table(table_ref(SILVER, "dim_location"))
                     .select("warehouse_id", "warehouse_name", "region"),
                 df.location_id == F.col("warehouse_id"), how="left")
    agg = df.groupBy("location_id", "warehouse_name", "region", "period_month").agg(
        F.sum("planned_output").alias("planned_units"),
        F.sum("actual_output").alias("actual_units"),
        F.round(F.avg("efficiency_pct"), 2).alias("avg_efficiency_pct"),
        F.sum("downtime_hours").alias("total_downtime_hours"),
    )
    agg.write.format("delta").mode("overwrite").saveAsTable(table_ref(SEMANTIC, "production_throughput_summary"))
    return agg.count()


