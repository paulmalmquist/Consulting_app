def _headers():
    return {"Authorization": f"Bearer {TOKEN}", "Content-Type": "application/json"}


def _get(path):
    r = requests.get(f"{HOST}{path}", headers=_headers(), timeout=30)
    r.raise_for_status()
    return r.json()


def _post(path, payload):
    r = requests.post(f"{HOST}{path}", json=payload, headers=_headers(), timeout=30)
    r.raise_for_status()
    return r.json()


def _post_raw(path, payload):
    r = requests.post(f"{HOST}{path}", json=payload, headers=_headers(), timeout=30)
    return r


def preflight():
    if not HOST or not TOKEN:
        print("ERROR: DATABRICKS_HOST and DATABRICKS_TOKEN are required.")
        sys.exit(1)
    if not CLUSTER_ID and not ALLOW_NEW_CLUSTER:
        print(
            "ERROR: DATABRICKS_CLUSTER_ID is required.\n"
            "Set it to a running all-purpose cluster ID, or set\n"
            "DATABRICKS_ALLOW_NEW_CLUSTER=true to provision an ephemeral cluster."
        )
        sys.exit(1)


def resolve_notebook_path():
    path = NOTEBOOK_PATH_CFG
    if "<your-email@domain.com>" in path:
        try:
            me = _get("/api/2.0/preview/scim/v2/Me")
            email = me.get("userName", "")
            if email:
                path = path.replace("<your-email@domain.com>", email)
                print(f"  auto-detected user email: {email}")
        except Exception as e:
            print(f"  warning: could not auto-detect email ({e}); using path as-is")
    return path.rstrip("/")


