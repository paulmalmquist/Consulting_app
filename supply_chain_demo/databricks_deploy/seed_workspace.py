def build_fact_inventory_position():
    df = spark.read.table(table_ref(BRONZE, "raw_inventory_snapshots"))
    df = df.withColumn("snapshot_date", F.to_date("snapshot_date"))
    df = df.filter(F.col("on_hand_qty") >= 0)
    df = df.withColumn("days_of_supply",
        F.when(F.col("avg_daily_demand") > 0,
               F.col("on_hand_qty") / F.col("avg_daily_demand")).otherwise(None)
    )
    df.write.format("delta").mode("overwrite").saveAsTable(table_ref(SILVER, "fact_inventory_position"))
    return df.count()

def build_fact_order_cycle():
    df = spark.read.table(table_ref(BRONZE, "raw_purchase_orders"))
    df = df.filter(F.col("po_date").isNotNull())
    df = df.filter(F.col("ordered_qty") > 0)
    df = df.withColumn("po_date", F.to_date("po_date"))
    w = Window.partitionBy("po_number").orderBy(F.col("po_date").desc())
    df = df.withColumn("_rn", F.row_number().over(w)).filter(F.col("_rn") == 1).drop("_rn")
    df.write.format("delta").mode("overwrite").saveAsTable(table_ref(SILVER, "fact_order_cycle"))
    return df.count()

def build_fact_shipment_event():
    df = spark.read.table(table_ref(BRONZE, "raw_shipments"))
    df = df.filter(F.col("ship_date").isNotNull())
    df = df.withColumn("ship_date", F.to_date("ship_date"))
    df = df.withColumn("delivery_date", F.to_date("delivery_date"))
    df = df.join(
        spark.read.table(table_ref(BRONZE, "raw_purchase_orders"))
            .filter(F.col("po_date").isNotNull())
            .filter(F.col("ordered_qty") > 0)
            .select("po_number", F.to_date("po_date").alias("po_date"), "ordered_qty"),
        on="po_number", how="left"
    )
    df = df.withColumn(
        "on_time", F.col("delivery_date") <= F.col("po_date") + F.expr("INTERVAL 14 DAYS")
    )
    df = df.withColumn(
        "in_full", F.col("shipped_qty") >= (F.col("ordered_qty") * F.lit(0.95))
    )
    df = df.withColumn("otif_flag", F.col("on_time") & F.col("in_full"))
    df.write.format("delta").mode("overwrite").saveAsTable(table_ref(SILVER, "fact_shipment_event"))
    return df.count()

def build_fact_production_output():
    df = spark.read.table(table_ref(BRONZE, "raw_production_events"))
    df = df.filter(F.col("actual_output") >= 0)
    df = df.withColumn("event_date", F.to_date("event_date"))
    df = df.withColumn(
        "efficiency_pct",
        F.when(F.col("planned_output") > 0,
               (F.col("actual_output") / F.col("planned_output")) * 100).otherwise(None)
    )
    df.write.format("delta").mode("overwrite").saveAsTable(table_ref(SILVER, "fact_production_output"))
    return df.count()

