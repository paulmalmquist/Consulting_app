def upload_notebook(path, script):
    encoded = base64.b64encode(script.encode("utf-8")).decode("utf-8")
    payload = {
        "path": path,
        "format": "SOURCE",
        "language": "PYTHON",
        "content": encoded,
        "overwrite": True,
    }
    r = _post_raw("/api/2.0/workspace/import", payload)
    if r.status_code not in (200, 201):
        print(f"ERROR: Upload failed ({r.status_code}): {r.text}")
        sys.exit(1)
    return path


def submit_run(notebook_path):
    cluster_spec = {}
    if CLUSTER_ID:
        cluster_spec = {"existing_cluster_id": CLUSTER_ID}
    else:
        cluster_spec = {
            "new_cluster": {
                "spark_version": "15.4.x-scala2.12",
                "node_type_id": "Standard_DS3_v2",
                "num_workers": 0,
                "spark_conf": {"spark.databricks.cluster.profile": "singleNode"},
                "custom_tags": {"ResourceClass": "SingleNode"},
            }
        }

    payload = {
        "run_name": "supply_chain_demo_seed",
        "tasks": [
            {
                "task_key": "seed_all_tables",
                "notebook_task": {"notebook_path": notebook_path},
                **cluster_spec,
            }
        ],
    }
    result = _post("/api/2.1/jobs/runs/submit", payload)
    return result["run_id"]


def poll_run(run_id):
    elapsed = 0
    while elapsed < TIMEOUT_SECONDS:
        info = _get(f"/api/2.1/jobs/runs/get?run_id={run_id}")
        state = info.get("state", {})
        life = state.get("life_cycle_state", "")
        result = state.get("result_state", "")

        if life == "TERMINATED":
            return result, info
        if life in ("INTERNAL_ERROR", "SKIPPED"):
            return life, info

        print(".", end="", flush=True)
        time.sleep(POLL_INTERVAL)
        elapsed += POLL_INTERVAL

    return "TIMEOUT", {}


def fetch_output(run_id):
    try:
        out = _get(f"/api/2.1/jobs/runs/get-output?run_id={run_id}")
        return out.get("notebook_output", {}).get("result", "")
    except Exception:
        return ""


def main():
    preflight()

    print("Supply Chain Demo — Databricks Seed")
    print(f"  Host:    {HOST}")
    print(f"  Catalog: {CATALOG}.{{{BRONZE},{SILVER},{SEMANTIC}}}")

    notebook_base = resolve_notebook_path()
    seed_path = f"{notebook_base}/seed_all_tables"

    print(f"\nBuilding embedded seed script...")
    script = build_seed_script()

    print(f"Uploading seed notebook to {seed_path}...")
    upload_notebook(seed_path, script)
    print("  ✓ uploaded")

    print("\nSubmitting Databricks run...")
    run_id = submit_run(seed_path)
    run_url = f"{HOST}/#job/runs/{run_id}"
    print(f"  run_id: {run_id}")
    print(f"  url:    {run_url}")
    print(f"\nPolling (every {POLL_INTERVAL}s, timeout {TIMEOUT_SECONDS}s)...")

    result_state, run_info = poll_run(run_id)
    print()

    if result_state == "SUCCESS":
        print("\n✓ Run completed successfully.")
        output = fetch_output(run_id)
        if output:
            print("\n" + output)
        else:
            print("(no notebook output captured — check run logs in the Databricks UI)")
    else:
        state_msg = run_info.get("state", {}).get("state_message", "")
        print(f"\n✗ Run ended with state: {result_state}")
        if state_msg:
            print(f"  {state_msg}")
        print(f"\nRun details: {run_url}")
        sys.exit(1)


if __name__ == "__main__":
    main()
