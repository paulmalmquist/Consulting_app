def build_data_quality_results():
    run_ts = str(datetime.now())
    checks = []

    def _check(name, tbl_schema, tbl_name, sql_pass, sql_fail, threshold_pct):
        tbl = table_ref(tbl_schema, tbl_name)
        try:
            total    = spark.sql(f"SELECT COUNT(*) AS c FROM {tbl}").collect()[0]["c"]
            failures = spark.sql(f"SELECT COUNT(*) AS c FROM {tbl} WHERE {sql_fail}").collect()[0]["c"]
            passes   = total - failures
            fail_pct = failures / max(total, 1)
            status   = "FAIL" if fail_pct > threshold_pct else "PASS"
        except Exception as e:
            total, passes, failures, status = 0, 0, 0, "ERROR"
        return (name, tbl, total, passes, failures, threshold_pct, status, run_ts)

    checks.append(_check("null_supplier_id_in_orders", SILVER, "fact_order_cycle",
                          "supplier_id IS NOT NULL", "supplier_id IS NULL", 0.01))
    checks.append(_check("null_ship_date_in_shipments", SILVER, "fact_shipment_event",
                          "ship_date IS NOT NULL", "ship_date IS NULL", 0.03))
    checks.append(_check("negative_on_hand", BRONZE, "raw_inventory_snapshots",
                          "on_hand_qty >= 0", "on_hand_qty < 0", 0.015))
    checks.append(_check("invalid_otif_range", SEMANTIC, "supplier_otif_scorecard",
                          "otif_pct BETWEEN 0 AND 100", "otif_pct NOT BETWEEN 0 AND 100", 0.0))
    checks.append(_check("missing_otif_flag", SILVER, "fact_shipment_event",
                          "otif_flag IS NOT NULL", "otif_flag IS NULL", 0.05))

    schema = StructType([
        StructField("check_name",     StringType(), True),
        StructField("table_name",     StringType(), True),
        StructField("total_records",  IntegerType(), True),
        StructField("pass_count",     IntegerType(), True),
        StructField("fail_count",     IntegerType(), True),
        StructField("threshold_pct",  DoubleType(), True),
        StructField("status",         StringType(), True),
        StructField("run_at",         StringType(), True),
    ])
    df = spark.createDataFrame(checks, schema)
    df.write.format("delta").mode("append").saveAsTable(table_ref(SEMANTIC, "data_quality_results"))
    return df.count()


