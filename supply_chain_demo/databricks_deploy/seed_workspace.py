def build_quarantine_records(quarantine_dfs, write_mode="overwrite"):
    valid = [q for q in quarantine_dfs if q is not None]
    if not valid:
        return 0
    combined = valid[0]
    for q in valid[1:]:
        combined = combined.union(q)
    combined.write.format("delta").mode(write_mode).saveAsTable(table_ref(SILVER, "quarantine_records"))
    return combined.count()


