#!/usr/bin/env python3
"""
Read the regressions artifact emitted by `eval_loop.runner --regressions-out`
and open one GitHub issue per (case_id, failure_category) tuple.

If an open issue already exists for that tuple (matched by a hidden marker
line in the body), add a recurrence comment instead of opening a duplicate.

Never opens a PR. Never pushes code. Issue-only signal.

Required env:
  GH_TOKEN   — token with `issues: write` scope on the repo

Usage:
  python scripts/eval_regressions_to_issues.py \\
    --input artifacts/eval-loop/regressions.json \\
    --repo owner/name \\
    --suite smoke \\
    --run-url https://github.com/.../actions/runs/123
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from typing import Any

MARKER_PREFIX = "<!-- winston-eval-marker: "
MARKER_SUFFIX = " -->"
LABEL = "winston-eval-regression"
MAX_ISSUES_PER_RUN = 5  # infra-failure safeguard per the plan
DEFAULT_ASSIGNEES: list[str] = []  # set if desired


def _marker(case_id: str, category: str) -> str:
    return f"{MARKER_PREFIX}case={case_id}|category={category}{MARKER_SUFFIX}"


def _title(case_id: str, category: str) -> str:
    return f"[eval-regression] {case_id}: {category}"


def _body(
    regression: dict[str, Any],
    run_url: str,
    suite: str,
    run_id: str | None,
    postgres_run_id: str | None,
) -> str:
    case_id = regression.get("case_id", "?")
    category = regression.get("failure_category", "?")
    mismatches = regression.get("mismatches") or []
    suspects = regression.get("suspected_files") or []

    body_lines = [
        _marker(case_id, category),
        "",
        f"**Case:** `{case_id}`",
        f"**Failure category:** `{category}`",
        f"**Suite:** `{suite}`",
        f"**Environment:** `{regression.get('environment') or '—'}`",
        "",
        f"**Runner run:** `{run_id}`",
    ]
    if postgres_run_id:
        body_lines.append(f"**Postgres run:** `{postgres_run_id}`")
    body_lines.extend(
        [
            f"**Workflow run:** {run_url}",
            "",
            "### Assertion failures",
            "",
        ]
    )
    if mismatches:
        for m in mismatches[:5]:
            body_lines.append(f"- {json.dumps(m, default=str)[:240]}")
    else:
        body_lines.append("_No structured mismatches — see run artifacts._")
    body_lines.extend(["", "### Suspect files", ""])
    if suspects:
        for s in suspects:
            body_lines.append(f"- `{s}`")
    else:
        body_lines.append("_No file suspects mapped._")
    body_lines.extend(
        [
            "",
            "### What to do",
            "",
            "1. Pull the run artifacts from the workflow run linked above "
            "(`artifacts/eval-loop/` has patch recommendations, receipt diffs, "
            "suspect heatmap).",
            "2. Query `winston_eval_results` filtered by this `case_id` to "
            "see full trace + `ai_gateway_log_id`.",
            "3. If this is an intentional contract change, invalidate the "
            "baseline via `POST /api/admin/eval/baselines/invalidate` with a reason.",
            "",
            "_Auto-generated by Winston eval. Will be updated on recurrence rather than duplicated._",
        ]
    )
    return "\n".join(body_lines)


def _gh(args: list[str], *, input_text: str | None = None) -> tuple[int, str, str]:
    proc = subprocess.run(
        args,
        capture_output=True,
        text=True,
        input=input_text,
        env=os.environ.copy(),
    )
    return proc.returncode, proc.stdout.strip(), proc.stderr.strip()


def _find_open_issue(repo: str, case_id: str, category: str) -> int | None:
    marker = _marker(case_id, category)
    # Search state:open issues with the marker in the body via gh search.
    rc, out, err = _gh(
        [
            "gh", "issue", "list",
            "--repo", repo,
            "--label", LABEL,
            "--state", "open",
            "--search", marker,
            "--json", "number,body",
            "--limit", "50",
        ]
    )
    if rc != 0:
        print(f"gh issue list failed: {err}", file=sys.stderr)
        return None
    try:
        issues = json.loads(out or "[]")
    except json.JSONDecodeError:
        return None
    for issue in issues:
        if marker in (issue.get("body") or ""):
            return int(issue["number"])
    return None


def _ensure_label(repo: str) -> None:
    _gh(
        [
            "gh", "label", "create", LABEL,
            "--repo", repo,
            "--color", "B60205",
            "--description", "Winston eval regression (auto-filed)",
        ]
    )
    # Ignore failure — label may already exist.


def _create_issue(repo: str, title: str, body: str) -> int | None:
    cmd = ["gh", "issue", "create", "--repo", repo, "--title", title, "--label", LABEL, "--body-file", "-"]
    for assignee in DEFAULT_ASSIGNEES:
        cmd.extend(["--assignee", assignee])
    rc, out, err = _gh(cmd, input_text=body)
    if rc != 0:
        print(f"gh issue create failed: {err}", file=sys.stderr)
        return None
    # Output ends with URL; extract issue number.
    last = out.splitlines()[-1] if out else ""
    try:
        return int(last.rstrip("/").rsplit("/", 1)[-1])
    except (ValueError, IndexError):
        return None


def _comment_recurrence(repo: str, number: int, run_url: str) -> None:
    body = f"Regression recurred. Workflow run: {run_url}"
    _gh(["gh", "issue", "comment", str(number), "--repo", repo, "--body", body])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--repo", required=True)
    parser.add_argument("--suite", required=True)
    parser.add_argument("--run-url", required=True)
    args = parser.parse_args()

    if not os.environ.get("GH_TOKEN"):
        print("GH_TOKEN not set — skipping issue creation.", file=sys.stderr)
        return 0

    try:
        payload = json.loads(open(args.input).read())
    except FileNotFoundError:
        print(f"No regressions file at {args.input}; nothing to file.")
        return 0
    except json.JSONDecodeError as exc:
        print(f"Could not parse {args.input}: {exc}", file=sys.stderr)
        return 0

    regressions = payload.get("regressions") or []
    if not regressions:
        print("No regressions to file.")
        return 0

    if len(regressions) > MAX_ISSUES_PER_RUN:
        print(
            f"::warning::{len(regressions)} regressions exceeds MAX_ISSUES_PER_RUN={MAX_ISSUES_PER_RUN}. "
            "Filing a single infra-failure issue instead.",
            file=sys.stderr,
        )
        _ensure_label(args.repo)
        infra_body = (
            f"{MARKER_PREFIX}infra-failure|run={payload.get('run_id')}{MARKER_SUFFIX}\n\n"
            f"More than {MAX_ISSUES_PER_RUN} regressions in a single run — "
            "likely an infrastructure or config failure, not real regressions.\n\n"
            f"Count: **{len(regressions)}**\n"
            f"Workflow run: {args.run_url}\n"
            f"Suite: `{args.suite}`\n\n"
            "Check: DATABASE_URL, API keys, backend health, scenario registry integrity."
        )
        _create_issue(
            args.repo,
            f"[eval-infra] {len(regressions)} regressions in {args.suite} run",
            infra_body,
        )
        return 0

    _ensure_label(args.repo)
    run_id = payload.get("run_id")
    postgres_run_id = payload.get("postgres_run_id")

    filed = 0
    recurred = 0
    for reg in regressions:
        case_id = reg.get("case_id")
        category = reg.get("failure_category")
        if not case_id or not category:
            continue
        existing = _find_open_issue(args.repo, case_id, category)
        body = _body(reg, args.run_url, args.suite, run_id, postgres_run_id)
        if existing:
            _comment_recurrence(args.repo, existing, args.run_url)
            recurred += 1
            print(f"recurrence comment on #{existing} for {case_id}/{category}")
        else:
            number = _create_issue(args.repo, _title(case_id, category), body)
            if number:
                filed += 1
                print(f"filed #{number} for {case_id}/{category}")

    print(f"Summary: {filed} new issues, {recurred} recurrences on existing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
